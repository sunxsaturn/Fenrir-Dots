-- Fenrir Desktop — Hyprland Lua configuration.
local home = os.getenv("HOME") or "/home"
local terminal = "kitty"
local fileManager = "thunar"
local launcher = "fuzzel"

hl.env("PATH", home .. "/.local/bin:/usr/local/bin:/usr/bin")
hl.env("XCURSOR_THEME", "Adwaita")
hl.env("XCURSOR_SIZE", "24")
hl.env("MOZ_ENABLE_WAYLAND", "1")
hl.env("QT_QPA_PLATFORMTHEME", "qt6ct")
hl.env("STARSHIP_CONFIG", home .. "/.config/fenrir/theme/starship.toml")
hl.env("XDG_CURRENT_DESKTOP", "Hyprland")
hl.env("XDG_SESSION_TYPE", "wayland")

hl.config({
  input = { kb_layout = "us", kb_variant = "intl", follow_mouse = 1 },
  general = { gaps_in = 5, gaps_out = 12, border_size = 2, layout = "dwindle" },
  decoration = {
    rounding = 12,
    active_opacity = 1.0,
    inactive_opacity = 1.0,
    blur = { enabled = false, size = 6, passes = 2, xray = false },
  },
  misc = { disable_hyprland_logo = true, vrr = 0 },
})

hl.bind("SUPER + Return", hl.dsp.exec_cmd(terminal))
hl.bind("SUPER + Space", hl.dsp.exec_cmd(launcher))
hl.bind("SUPER + E", hl.dsp.exec_cmd(fileManager))
hl.bind("SUPER + W", hl.dsp.exec_cmd("fenrir-wallpaper next"))
hl.bind("SUPER + A", hl.dsp.exec_cmd("fenrir-doctor"))
hl.bind("SUPER + S", hl.dsp.exec_cmd("fenrir-control-center"))
hl.bind("SUPER + SHIFT + G", hl.dsp.exec_cmd("fenrir-glass enable"))
hl.bind("SUPER + CTRL + SHIFT + G", hl.dsp.exec_cmd("fenrir-glass disable"))
hl.bind("SUPER + L", hl.dsp.exec_cmd("hyprlock"))
hl.bind("SUPER + Q", hl.dsp.window.close())
hl.bind("SUPER + SHIFT + Q", hl.dsp.exec_cmd("hyprctl dispatch exit"))
hl.bind("Print", hl.dsp.exec_cmd("grim - | wl-copy"))

-- Wallpaper-derived accent tokens are generated by fenrir-theme.
local themeConfig = loadfile(home .. "/.config/hypr/fenrir-theme.lua")
if themeConfig then pcall(themeConfig) end

-- The glass mode is generated by fenrir-glass and can be toggled without editing source.
local glassConfig = loadfile(home .. "/.config/hypr/fenrir-glass.lua")
if glassConfig then pcall(glassConfig) end
