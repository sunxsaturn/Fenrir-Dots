-- Fenrir Desktop — Hyprland 0.57+ Lua configuration.
-- Keep this file intentionally hardware-neutral; add monitor-specific rules in monitors.lua.

local home = os.getenv("HOME") or "/home"
local mainMod = "SUPER"
local terminal = "kitty"
local fileManager = "thunar"
local launcher = "fuzzel"
local browser = "firefox-nightly"

-- Environment must be prepared before Wayland clients start.
hl.env("PATH", home .. "/.local/bin:/usr/local/sbin:/usr/local/bin:/usr/bin")
hl.env("XCURSOR_THEME", "Adwaita")
hl.env("XCURSOR_SIZE", "24")
hl.env("HYPRCURSOR_SIZE", "24")
hl.env("GTK_THEME", "adw-gtk3-dark")
hl.env("QT_QPA_PLATFORM", "wayland;xcb")
hl.env("MOZ_ENABLE_WAYLAND", "1")
hl.env("XDG_CURRENT_DESKTOP", "Hyprland")
hl.env("XDG_SESSION_DESKTOP", "Hyprland")
hl.env("XDG_SESSION_TYPE", "wayland")

require("./fimbulwinter")
require("./monitors")

-- Core input and tiling behavior.
hl.config({
    input = {
        kb_layout = "us",
        kb_variant = "intl",
        follow_mouse = 1,
        sensitivity = 0,
        accel_profile = "flat",
        touchpad = {
            natural_scroll = true,
            tap_to_click = true,
        },
    },
    general = {
        gaps_in = 5,
        gaps_out = 12,
        border_size = 2,
        resize_on_border = true,
        allow_tearing = false,
        layout = "dwindle",
    },
    dwindle = {
        pseudotile = true,
        preserve_split = true,
    },
    cursor = {
        inactive_timeout = 4,
    },
    misc = {
        disable_hyprland_logo = true,
        vrr = 0,
    },
})

-- Persistent user preferences generated by Fenrir Settings.
local fenrirRuntime = loadfile(home .. "/.config/hypr/fenrir-settings.lua")
if fenrirRuntime then pcall(fenrirRuntime) end

-- Smooth, short animations: avoid heavy blur/animation effects that waste GPU time.
hl.curve("fenrirEase", { type = "bezier", points = { {0.20, 0.80}, {0.20, 1.00} } })
hl.curve("fenrirLinear", { type = "bezier", points = { {0.00, 0.00}, {1.00, 1.00} } })
hl.animation({ leaf = "global", enabled = true, speed = 8, bezier = "default" })
hl.animation({ leaf = "border", enabled = true, speed = 5, bezier = "fenrirEase" })
hl.animation({ leaf = "windows", enabled = true, speed = 4, bezier = "fenrirEase" })
hl.animation({ leaf = "windowsIn", enabled = true, speed = 4, bezier = "fenrirEase", style = "popin 85%" })
hl.animation({ leaf = "windowsOut", enabled = true, speed = 3, bezier = "fenrirLinear", style = "popin 85%" })
hl.animation({ leaf = "fade", enabled = true, speed = 3, bezier = "fenrirEase" })
hl.animation({ leaf = "workspaces", enabled = true, speed = 4, bezier = "fenrirEase", style = "slide" })

-- Fimbulwinter Glass layers use their CSS opacity and receive compositor blur.
hl.layer_rule({ match = { namespace = "waybar" }, blur = true, ignore_alpha = 0.10 })
hl.layer_rule({ match = { namespace = "mako" }, blur = true, ignore_alpha = 0.10 })
hl.layer_rule({ match = { namespace = "fuzzel" }, blur = true, ignore_alpha = 0.10 })

-- Sun AI opens in the user-selected browser and remains bound to localhost.

-- Application launch and session controls.
hl.bind(mainMod .. " + Return", hl.dsp.exec_cmd(terminal))
hl.bind(mainMod .. " + Space", hl.dsp.exec_cmd(launcher))
hl.bind(mainMod .. " + E", hl.dsp.exec_cmd(fileManager))
hl.bind(mainMod .. " + B", hl.dsp.exec_cmd(browser))
hl.bind(mainMod .. " + A", hl.dsp.exec_cmd("sun-ai open"))
hl.bind(mainMod .. " + W", hl.dsp.exec_cmd("fenrir-wallpaper next"))
hl.bind(mainMod .. " + SHIFT + W", hl.dsp.exec_cmd("fenrir-wallpaper next"))
hl.bind(mainMod .. " + L", hl.dsp.exec_cmd("hyprlock"))
hl.bind(mainMod .. " + SHIFT + R", hl.dsp.exec_cmd("hyprctl reload"))
hl.bind(mainMod .. " + SHIFT + Q", hl.dsp.exec_cmd("hyprctl dispatch exit"))
hl.bind(mainMod .. " + Q", hl.dsp.window.close())
hl.bind(mainMod .. " + F", hl.dsp.window.fullscreen({ action = "toggle" }))
hl.bind(mainMod .. " + P", hl.dsp.window.pseudo())
hl.bind(mainMod .. " + J", hl.dsp.layout("togglesplit"))
hl.bind(mainMod .. " + SHIFT + S", hl.dsp.exec_cmd("sh -lc 'grim -g \"$(slurp)\" - | wl-copy'"))
hl.bind(mainMod .. " + V", hl.dsp.exec_cmd("sh -lc 'cliphist list | fuzzel --dmenu | cliphist decode | wl-copy'"))
hl.bind(mainMod .. " + SHIFT + F9", hl.dsp.exec_cmd("fenrir-record toggle"))
hl.bind("Print", hl.dsp.exec_cmd("grim - | wl-copy"))

-- Directional focus and window movement.
hl.bind(mainMod .. " + left", hl.dsp.focus({ direction = "left" }))
hl.bind(mainMod .. " + right", hl.dsp.focus({ direction = "right" }))
hl.bind(mainMod .. " + up", hl.dsp.focus({ direction = "up" }))
hl.bind(mainMod .. " + down", hl.dsp.focus({ direction = "down" }))

-- Workspace and custom keybindings are user-managed, separate files.
local workspaceBindings = loadfile(home .. "/.config/hypr/fenrir-workspaces.lua")
if workspaceBindings then pcall(workspaceBindings) end
local customBindings = loadfile(home .. "/.config/hypr/fenrir-custom.lua")
if customBindings then pcall(customBindings) end

hl.bind(mainMod .. " + mouse:272", hl.dsp.window.drag(), { mouse = true })
hl.bind(mainMod .. " + mouse:273", hl.dsp.window.resize(), { mouse = true })

-- Audio and display controls.
hl.bind("XF86AudioRaiseVolume", hl.dsp.exec_cmd("wpctl set-volume -l 1.0 @DEFAULT_AUDIO_SINK@ 5%+"), { locked = true, repeating = true })
hl.bind("XF86AudioLowerVolume", hl.dsp.exec_cmd("wpctl set-volume @DEFAULT_AUDIO_SINK@ 5%-"), { locked = true, repeating = true })
hl.bind("XF86AudioMute", hl.dsp.exec_cmd("wpctl set-mute @DEFAULT_AUDIO_SINK@ toggle"), { locked = true, repeating = true })
hl.bind("XF86AudioMicMute", hl.dsp.exec_cmd("wpctl set-mute @DEFAULT_AUDIO_SOURCE@ toggle"), { locked = true, repeating = true })
hl.bind("XF86AudioPlay", hl.dsp.exec_cmd("playerctl play-pause"), { locked = true })
hl.bind("XF86AudioNext", hl.dsp.exec_cmd("playerctl next"), { locked = true })
hl.bind("XF86AudioPrev", hl.dsp.exec_cmd("playerctl previous"), { locked = true })
hl.bind("XF86MonBrightnessUp", hl.dsp.exec_cmd("brightnessctl -e4 -n2 set 5%+"), { locked = true, repeating = true })
hl.bind("XF86MonBrightnessDown", hl.dsp.exec_cmd("brightnessctl -e4 -n2 set 5%-"), { locked = true, repeating = true })

-- Start only session components. Hyprland/systemd owns graphical-session.target;
-- the wallpaper service has bounded retries while hyprpaper starts.
hl.on("hyprland.start", function()
    hl.exec_cmd("dbus-update-activation-environment --systemd WAYLAND_DISPLAY XDG_CURRENT_DESKTOP HYPRLAND_INSTANCE_SIGNATURE")
    hl.exec_cmd("systemctl --user import-environment WAYLAND_DISPLAY XDG_CURRENT_DESKTOP HYPRLAND_INSTANCE_SIGNATURE")
    hl.exec_cmd("hyprpaper")
    hl.exec_cmd("mako")
    hl.exec_cmd("systemctl --user start fenrir-stay-awake.service")
    hl.exec_cmd("systemctl --user start hyprpolkitagent")
    hl.exec_cmd("waybar")
    hl.exec_cmd("nm-applet --indicator")
    hl.exec_cmd("blueman-applet")
    hl.exec_cmd("dex --autostart")
    hl.exec_cmd("systemctl --user start fenrir-wallpaper.service")
    hl.exec_cmd("fenrir-monitor")
    hl.exec_cmd("fenrir-welcome --once")
end)
