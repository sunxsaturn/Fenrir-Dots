"""Generate a reversible Hyprland Lua glass profile."""
from __future__ import annotations

from pathlib import Path
import subprocess

DEFAULT_OPACITY = 0.60
GLASS_APPS = ("kitty", "firefox", "firefox-nightly", "thunar", "fuzzel", "waybar", "mako")
PROTECTED_CLASSES = ("^(steam|steam_app_.*|gamescope|mpv|vlc|hyprlock|polkit-.*)$")


def render_glass(enabled: bool, opacity: float = DEFAULT_OPACITY) -> str:
    if not 0.55 <= opacity <= 1.0:
        raise ValueError("glass opacity must be between 0.55 and 1.0")
    if not enabled:
        return "-- Fimbulwinter Glass disabled by the user.\n"
    opacity_value = f"{opacity:.2f}"
    lines = [
        "-- Generated by fenrir-glass. Do not edit this file by hand.",
        "hl.config({",
        "  decoration = {",
        "    blur = {",
        "      enabled = true,",
        "      size = 8,",
        "      passes = 2,",
        "      xray = false,",
        "      ignore_opacity = false,",
        "      vibrancy = 0.12,",
        "    },",
        "  },",
        "})",
        "hl.window_rule({",
        '  name = "fenrir-glass-default",',
        '  match = { class = ".*" },',
        f'  opacity = "{opacity_value} override {opacity_value} override 1.0 override",',
        "})",
        "hl.window_rule({",
        '  name = "fenrir-glass-protected",',
        f'  match = {{ class = "{PROTECTED_CLASSES}" }},',
        '  opacity = "1.0 override 1.0 override 1.0 override",',
        "})",
        'hl.layer_rule({ name = "fenrir-glass-top", match = { namespace = "fenrir-top" }, blur = true, ignore_alpha = 0.10 })',
        'hl.layer_rule({ name = "fenrir-glass-dock", match = { namespace = "fenrir-dock" }, blur = true, ignore_alpha = 0.10 })',
        'hl.layer_rule({ name = "fenrir-glass-waybar", match = { namespace = "waybar" }, blur = true, ignore_alpha = 0.10 })',
        'hl.layer_rule({ name = "fenrir-glass-fuzzel", match = { namespace = "fuzzel" }, blur = true, ignore_alpha = 0.10 })',
        'hl.layer_rule({ name = "fenrir-glass-mako", match = { namespace = "mako" }, blur = true, ignore_alpha = 0.10 })',
    ]
    return "\n".join(lines) + "\n"


def set_glass(enabled: bool, opacity: float = DEFAULT_OPACITY, config_path: Path | str | None = None) -> Path:
    path = Path(config_path or Path.home() / ".config/hypr/fenrir-glass.lua")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_glass(enabled, opacity), encoding="utf-8")
    return path


def reload_hyprland() -> bool:
    try:
        result = subprocess.run(
            ["hyprctl", "reload"], check=False, capture_output=True, text=True, timeout=8
        )
    except (OSError, subprocess.TimeoutExpired):
        return False
    return result.returncode == 0
