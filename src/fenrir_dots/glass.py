"""Generate supported Fimbulwinter glass adapters from one preference file."""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import tempfile
from pathlib import Path
from typing import Any

DEFAULT_SETTINGS: dict[str, Any] = {
    "schema": "org.fenrir.desktop-appearance.v1",
    "theme": "fimbulwinter-obsidian",
    "accent_source": "current-wallpaper",
    "glass": {"enabled": True, "surface_opacity": 0.80, "blur_px": 24},
    "accessibility": {"minimum_text_contrast": 4.5, "high_contrast_fallback": True},
    "performance": {"gaming_blur_suppression": True, "max_blur_passes": 2},
}


def _atomic_json(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            json.dump(data, stream, indent=2)
            stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temporary, 0o600)
        os.replace(temporary, path)
    except Exception:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def _atomic_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    except Exception:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def _load_settings(path: Path) -> dict[str, Any]:
    if not path.exists():
        _atomic_json(path, DEFAULT_SETTINGS)
    data = json.loads(path.read_text(encoding="utf-8"))
    if data.get("schema") != DEFAULT_SETTINGS["schema"]:
        raise ValueError("Unsupported Fenrir appearance settings schema")
    glass = data.get("glass")
    if not isinstance(glass, dict) or not isinstance(glass.get("enabled"), bool):
        raise ValueError("Invalid glass settings")
    opacity = glass.get("surface_opacity")
    if isinstance(opacity, bool) or not isinstance(opacity, (float, int)) or not 0.45 <= opacity <= 1.0:
        raise ValueError("Glass surface_opacity must be between 0.45 and 1.0")
    blur = glass.get("blur_px")
    if isinstance(blur, bool) or not isinstance(blur, int) or not 0 <= blur <= 40:
        raise ValueError("Glass blur_px must be an integer between 0 and 40")
    return data


def render_adapters(home: Path, settings: dict[str, Any]) -> None:
    glass = settings["glass"]
    enabled = glass["enabled"]
    opacity = float(glass["surface_opacity"]) if enabled else 1.0
    blur_px = int(glass["blur_px"]) if enabled else 0
    surface = f"rgba(9, 11, 18, {opacity:.2f})"
    elevated = f"rgba(20, 23, 36, {min(1.0, opacity + 0.08):.2f})"

    _atomic_text(
        home / ".config/kitty/fenrir-glass.conf",
        f"# Generated by fenrir-glass; edit appearance.json instead.\nbackground_opacity {opacity:.2f}\n",
    )
    gtk_css = (
        "/* Generated by fenrir-glass; keep text fully opaque. */\n"
        f"@define-color fenrir_surface {surface};\n"
        f"@define-color fenrir_elevated {elevated};\n"
        "window, dialog, .background { background-color: @fenrir_surface; }\n"
        "popover, menu, tooltip { background-color: @fenrir_elevated; }\n"
    )
    for version in ("gtk-3.0", "gtk-4.0"):
        _atomic_text(home / f".config/{version}/fenrir-glass.css", gtk_css)

    _atomic_text(
        home / ".config/waybar/fenrir-glass.css",
        "/* Generated by fenrir-glass. */\n"
        f"@define-color fenrir_surface {surface};\n"
        f"@define-color fenrir_elevated {elevated};\n",
    )
    _atomic_text(
        home / ".config/hypr/fenrir-glass.conf",
        "# Generated by fenrir-glass; do not edit manually.\n"
        "decoration {\n"
        f"  blur {{ enabled = {'yes' if enabled else 'no'}; size = {max(2, blur_px // 2)}; passes = 2; }}\n"
        "}\n"
        f"layerrule = blur, waybar\nlayerrule = blur, fuzzel\nlayerrule = blur, mako\n"
        if enabled else
        "# Generated by fenrir-glass; glass effects are disabled.\n"
        "decoration { blur { enabled = no; } }\n"
    )


def apply(command: str, home: Path | None = None) -> tuple[bool, float]:
    home = home or Path.home()
    settings_path = home / ".config/fenrir/appearance.json"
    settings = _load_settings(settings_path)
    current = settings["glass"]["enabled"]
    if command == "on":
        enabled = True
    elif command == "off":
        enabled = False
    elif command == "toggle":
        enabled = not current
    elif command == "status":
        render_adapters(home, settings)
        return current, float(settings["glass"]["surface_opacity"])
    else:
        raise ValueError(f"Unknown glass action: {command}")

    settings["glass"]["enabled"] = enabled
    _atomic_json(settings_path, settings)
    render_adapters(home, settings)
    # Reload Hyprland when available; this is best-effort and never blocks the
    # saved preference if the user is outside a Hyprland session.
    hyprctl = shutil.which("hyprctl")
    if hyprctl and os.environ.get("HYPRLAND_INSTANCE_SIGNATURE"):
        subprocess.run([hyprctl, "reload"], check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return enabled, float(settings["glass"]["surface_opacity"])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="fenrir-glass")
    parser.add_argument("action", choices=("on", "off", "toggle", "status"))
    args = parser.parse_args(argv)
    try:
        enabled, opacity = apply(args.action)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        parser.error(str(exc))
    state = "enabled" if enabled else "disabled"
    print(f"Fimbulwinter glass {state}; surface opacity {opacity:.0%} when enabled.")
    print("GTK, Kitty, Waybar and eligible Hyprland surfaces are configured.")
    print("Restart already-open GTK/Kitty/Waybar applications to apply their new styling.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
